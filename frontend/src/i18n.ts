function normalize(value: string) {
  return value
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^\p{L}\p{N}_]+/gu, ' ')
    .trim();
}

export function isLanguage(value: string | null): value is Language {
  return value === 'en' || value === 'fr' || value === 'ar';
}

export function isThemeMode(value: string | null): value is ThemeMode {
  return value === 'light' || value === 'dark';
}

export function currentLanguage(): Language {
  if (typeof document !== 'undefined' && isLanguage(document.documentElement.lang)) return document.documentElement.lang;
  if (typeof localStorage !== 'undefined') {
    const saved = localStorage.getItem('agencyos_language');
    if (isLanguage(saved)) return saved;
  }
  return 'fr';
}

export function tr(key: string, language: Language = currentLanguage()) {
  return commonText[language][key] ?? commonText.en[key] ?? key;
}

export function trStatus(value: string | null | undefined, language: Language = currentLanguage()) {
  if (!value) return '';
  return trLoose(String(value).replace(/_/g, ' '), language);
}

export function trLoose(value: string | null | undefined, language: Language = currentLanguage()) {
  if (!value) return '';
  const clean = String(value).trim();
  const key = looseKeys[normalize(clean)];
  return key ? tr(key, language) : clean;
}
